def _scalar_array(mesh: Any, specification: Mapping[str, Any], context: str) -> np.ndarray:
    name = specification["name"]
    association = specification["association"]
    source = mesh.point_data if association == "point" else mesh.cell_data
    expected = len(mesh.points) if association == "point" else len(mesh.triangles)
    if name not in source:
        available = ", ".join(sorted(source)) or "<none>"
        raise CohortInputError(
            f"{context}: declared {association} array {name!r} is absent; "
            f"available arrays: {available}"
        )
    values = np.asarray(source[name])
    component = specification.get("component")
    if values.ndim == 1:
        if component not in {None, 0}:
            raise CohortInputError(f"{context}: scalar array {name!r} has no component {component}")
        result = values
    elif values.ndim == 2:
        if component is None:
            if values.shape[1] != 1:
                raise CohortInputError(
                    f"{context}: multicomponent array {name!r} needs an explicit component"
                )
            result = values[:, 0]
        elif component >= values.shape[1]:
            raise CohortInputError(
                f"{context}: component {component} is outside array {name!r} shape {values.shape}"
            )
        else:
            result = values[:, component]
    else:
        raise CohortInputError(f"{context}: unsupported scalar-array shape {values.shape}")
    if result.shape != (expected,):
        raise CohortInputError(
            f"{context}: {association} array {name!r} length {len(result)} != {expected}"
        )
    try:
        result = np.asarray(result, dtype=float)
    except (TypeError, ValueError) as exc:
        raise CohortInputError(f"{context}: point array {name!r} is not numeric") from exc
    finite = np.isfinite(result)
    if not specification.get("allow_nan", False) and not np.all(finite):
        raise CohortInputError(f"{context}: array {name!r} contains non-finite values")
    if not np.any(finite):
        raise CohortInputError(f"{context}: point array {name!r} has no finite values")
    lo, hi = map(float, specification["valid_range"])
    tolerance = 64.0 * np.finfo(float).eps * max(1.0, abs(lo), abs(hi))
    if np.any(result[finite] < lo - tolerance) or np.any(result[finite] > hi + tolerance):
        raise CohortInputError(
            f"{context}: array {name!r} leaves declared range [{lo:g},{hi:g}]"
        )
    if specification["meaning"] == "binary_scar":
        allowed = np.asarray(
            specification["barrier_values"] + specification["viable_values"], dtype=float
        )
        distance = np.min(np.abs(result[finite, None] - allowed[None, :]), axis=1)
        if np.any(distance > tolerance):
            raise CohortInputError(
                f"{context}: binary array {name!r} contains undeclared class values"
            )
    return result


def normalise_barrier_observation(
    values: np.ndarray, specification: Mapping[str, Any]
) -> np.ndarray:
    """Map explicitly declared observations to the common score [-1,1]."""
    result = np.full(values.shape, np.nan, dtype=float)
    finite = np.isfinite(values)
    meaning = specification["meaning"]
    higher_barrier = specification["higher_means"] == "barrier"
    if meaning == "barrier_score":
        lo, hi = map(float, specification["valid_range"])
        scaled = 2.0 * (values[finite] - lo) / (hi - lo) - 1.0
        result[finite] = scaled if higher_barrier else -scaled
    elif meaning == "scar_probability":
        lo, hi = map(float, specification["valid_range"])
        probability = (values[finite] - lo) / (hi - lo)
        scaled = 2.0 * probability - 1.0
        result[finite] = scaled if higher_barrier else -scaled
    elif meaning == "binary_scar":
        barrier_values = np.asarray(specification["barrier_values"], dtype=float)
        viable_values = np.asarray(specification["viable_values"], dtype=float)
        for value in barrier_values:
            result[np.isclose(values, value, rtol=0.0, atol=1.0e-12)] = 1.0
        for value in viable_values:
            result[np.isclose(values, value, rtol=0.0, atol=1.0e-12)] = -1.0
        if not higher_barrier:
            result[finite] *= -1.0
    else:
        raise CohortInputError(f"cannot normalise meaning {meaning!r} as a barrier score")
    return result


def barrier_probability_from_state(state: np.ndarray) -> np.ndarray:
    """Return the scoring readout without modifying or constraining the PDE state."""
    values = np.asarray(state, dtype=float)
    if not np.all(np.isfinite(values)):
        raise CohortInputError("reconstructed PDE state contains a non-finite value")
    return 0.5 * (1.0 + np.clip(values, -1.0, 1.0))


def _cell_values_at_nodes(
    mesh: Any,
    cell_values: np.ndarray,
    specification: Mapping[str, Any],
    context: str,
) -> np.ndarray:
    """Apply one explicitly declared cell-to-node reduction."""
    triangles = np.asarray(mesh.triangles, dtype=np.int64)
    areas = np.asarray(mesh.triangle_areas(), dtype=float)
    reduction = specification["cell_to_point_reduction"]
    n_vertices = len(mesh.points)
    if reduction == "area_weighted_mean":
        numerator = np.zeros(n_vertices, dtype=float)
        denominator = np.zeros(n_vertices, dtype=float)
        finite = np.isfinite(cell_values)
        for local in range(3):
            np.add.at(
                numerator,
                triangles[finite, local],
                areas[finite] * cell_values[finite],
            )
            np.add.at(denominator, triangles[finite, local], areas[finite])
        result = np.full(n_vertices, np.nan, dtype=float)
        present = denominator > 0.0
        result[present] = numerator[present] / denominator[present]
        return result
    if reduction == "maximum":
        result = np.full(n_vertices, -np.inf, dtype=float)
        finite = np.isfinite(cell_values)
        for local in range(3):
            np.maximum.at(result, triangles[finite, local], cell_values[finite])
        result[~np.isfinite(result)] = np.nan
        return result
    if reduction == "majority":
        barrier_values = np.asarray(specification["barrier_values"], dtype=float)
        viable_values = np.asarray(specification["viable_values"], dtype=float)
        is_barrier = np.any(np.isclose(cell_values[:, None], barrier_values[None, :]), axis=1)
        is_viable = np.any(np.isclose(cell_values[:, None], viable_values[None, :]), axis=1)
        barrier_area = np.zeros(n_vertices, dtype=float)
        viable_area = np.zeros(n_vertices, dtype=float)
        for local in range(3):
            np.add.at(barrier_area, triangles[is_barrier, local], areas[is_barrier])
            np.add.at(viable_area, triangles[is_viable, local], areas[is_viable])
        tied = np.isclose(barrier_area, viable_area, rtol=1.0e-12, atol=1.0e-14)
        if np.any(tied):
            raise CohortInputError(
                f"{context}: area-weighted majority reduction has {np.count_nonzero(tied)} ties"
            )
        # Emit the first explicitly declared class value; normalisation below
        # uses class membership rather than its numeric order.
        result = np.where(
            barrier_area > viable_area,
            float(barrier_values[0]),
            float(viable_values[0]),
        )
        return np.asarray(result, dtype=float)
    raise CohortInputError(f"{context}: unsupported cell-to-point reduction {reduction!r}")


def barrier_observation_at_nodes(
    mesh: Any, specification: Mapping[str, Any], context: str
) -> tuple[np.ndarray, np.ndarray]:
    """Return raw declared values and their explicitly reduced nodal score."""
    raw = _scalar_array(mesh, specification, context)
    if specification["association"] == "point":
        return raw, normalise_barrier_observation(raw, specification)
    reduction = specification["cell_to_point_reduction"]
    if specification["meaning"] == "binary_scar" and reduction != "majority":
        cell_score = normalise_barrier_observation(raw, specification)
        return raw, _cell_values_at_nodes(mesh, cell_score, specification, context)
    nodal_raw = _cell_values_at_nodes(mesh, raw, specification, context)
    return raw, normalise_barrier_observation(nodal_raw, specification)


def validity_mask_at_nodes(
    mesh: Any, specification: Mapping[str, Any], context: str
) -> np.ndarray:
    name = specification["name"]
    if name not in mesh.point_data:
        available = ", ".join(sorted(mesh.point_data)) or "<none>"
        raise CohortInputError(
            f"{context}: declared point array {name!r} is absent; available arrays: {available}"
        )
    values = np.asarray(mesh.point_data[name])
    if values.ndim == 2 and values.shape[1] == 1:
        values = values[:, 0]
    if values.shape != (len(mesh.points),):
        raise CohortInputError(f"{context}: validity mask {name!r} must be scalar point data")
    valid_values = np.asarray(specification["valid_values"])
    invalid_values = np.asarray(specification["invalid_values"])
    valid = np.isin(values, valid_values)
    invalid = np.isin(values, invalid_values)
    if np.any(valid & invalid) or not np.all(valid | invalid):
        raise CohortInputError(
            f"{context}: validity mask {name!r} contains an undeclared or ambiguous value"
        )
    return np.asarray(valid, dtype=bool)


def validate_fibre_array(mesh: Any, specification: Mapping[str, Any], context: str) -> None:
    name = specification["name"]
    association = specification["association"]
    source = mesh.point_data if association == "point" else mesh.cell_data

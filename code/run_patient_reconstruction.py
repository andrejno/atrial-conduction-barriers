def command_prepare_masks(args: argparse.Namespace) -> None:
    manifest = load_manifest(args.manifest)
    lock = _require_holdout_unlock(args)
    _check_lock_linkage(lock, args.manifest, manifest)
    selected_ids = _partition_ids(args.partition)
    inventory, prepared = validate_cohort(
        args.cohort_root.resolve(),
        manifest,
        patient_ids=selected_ids,
        expose_holdout_summaries=args.partition != "development",
    )
    output = args.output_dir.resolve()
    if args.partition != "development" and output.exists() and any(output.iterdir()):
        raise CohortInputError(
            "locked-holdout mask directory must be new or empty (write-once rule)"
        )
    output.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, Any]] = []
    inventory_by_id = {row["patient_id"]: row for row in inventory}
    manifest_sha256 = _sha256_file(args.manifest)
    analysis_plan_sha256 = (
        args.expected_plan_sha256 if args.partition != "development" else ""
    )
    design = manifest["mask_design"]
    variants: list[tuple[str, float, float]] = [
        ("primary", float(design["sector_fraction"]), float(design["band_width_mm"]))
    ]
    variants.extend(
        (f"sector_{float(value):g}", float(value), float(design["band_width_mm"]))
        for value in design.get("secondary_sector_fractions", [])
    )
    variants.extend(
        (f"band_{float(value):g}mm", float(design["sector_fraction"]), float(value))
        for value in design.get("secondary_band_widths_mm", [])
    )
    for patient_id in selected_ids:
        mesh, barrier, boundaries = prepared[patient_id]
        node_area = _node_area_weights(mesh)
        for replicate in range(int(manifest["mask_design"]["replicates"])):
            for pv_label in CANONICAL_PV_LABELS:
                for variant, fraction, band in variants:
                    mask = prepare_patient_mask(
                        patient_id,
                        mesh,
                        barrier,
                        boundaries,
                        manifest,
                        replicate,
                        pv_label,
                        mask_variant=variant,
                        sector_fraction=fraction,
                        band_width_mm=band,
                    )
                    filename = f"{patient_id}_{pv_label}_mask_{replicate:02d}_{variant}.npz"
                    np.savez_compressed(
                        output / filename,
                        training=mask.training,
                        guard=mask.guard,
                        evaluation=mask.evaluation,
                        selected_boundary=mask.selected_boundary,
                    )
                    row = dict(mask.metadata)
                    row.update(
                        {
                            "training_area_mm2": float(node_area[mask.training].sum()),
                            "guard_area_mm2": float(node_area[mask.guard].sum()),
                            "evaluation_area_mm2": float(node_area[mask.evaluation].sum()),
                            "post_mesh_sha256": inventory_by_id[patient_id]["post_sha256"],
                            "input_manifest_sha256": manifest_sha256,
                            "analysis_plan_sha256": analysis_plan_sha256,
                            "npz_path": filename,
                        }
                    )
                    rows.append(row)
    _write_csv(output / "patient_mask_manifest.csv", MASK_COLUMNS, rows)
    print(f"prepared {len(rows)} deterministic masks in {output}")


def _parse_manifest_integer(value: str, field: str, row_number: int) -> int:
    try:
        parsed = int(value)
    except ValueError as exc:
        raise CohortInputError(
            f"mask-manifest row {row_number} field {field} is not an integer"
        ) from exc
    return parsed


def _parse_manifest_float(value: str, field: str, row_number: int) -> float:
    try:
        parsed = float(value)
    except ValueError as exc:
        raise CohortInputError(
            f"mask-manifest row {row_number} field {field} is not numeric"
        ) from exc
    if not np.isfinite(parsed):
        raise CohortInputError(
            f"mask-manifest row {row_number} field {field} is non-finite"
        )
    return parsed


def _read_primary_mask_rows(
    mask_directory: Path,
    patient_ids: Sequence[str],
    manifest_path: Path,
    manifest: Mapping[str, Any],
    inventory_by_id: Mapping[str, Mapping[str, Any]],
    expected_lock_sha256: str | None,
) -> dict[tuple[str, str, int], dict[str, str]]:
    """Read metadata only; every NPZ is independently re-derived when used."""
    path = mask_directory / "patient_mask_manifest.csv"
    if not path.is_file():
        raise CohortInputError(f"prepared-mask manifest does not exist: {path}")
    manifest_digest = _sha256_file(manifest_path)
    selected = set(patient_ids)
    primary: dict[tuple[str, str, int], dict[str, str]] = {}
    seen_all: set[tuple[str, str, int, str]] = set()
    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames is None or tuple(reader.fieldnames) != MASK_COLUMNS:
            raise CohortInputError(
                "prepared-mask CSV header differs from the immutable mask schema"
            )
        for row_number, row in enumerate(reader, start=2):
            patient_id = row["patient_id"]
            pv_label = row["pv_label"]
            if patient_id not in EXPECTED_IDS or pv_label not in CANONICAL_PV_LABELS:
                raise CohortInputError(
                    f"mask-manifest row {row_number} has an unknown patient or PV label"
                )
            replicate = _parse_manifest_integer(row["replicate"], "replicate", row_number)
            if not 0 <= replicate < int(manifest["mask_design"]["replicates"]):
                raise CohortInputError(
                    f"mask-manifest row {row_number} has an out-of-range replicate"
                )
            all_key = (patient_id, pv_label, replicate, row["mask_variant"])
            if all_key in seen_all:
                raise CohortInputError(f"duplicate mask-manifest row for {all_key}")
            seen_all.add(all_key)
            if row["mask_variant"] != "primary" or patient_id not in selected:
                continue
            expected_partition = (
                "development" if patient_id in DEVELOPMENT_IDS else "locked_holdout"
            )
            if row["partition"] != expected_partition:
                raise CohortInputError(
                    f"mask-manifest row {row_number} has an incorrect partition"
                )
            exact_numeric = {
                "seed": int(manifest["mask_design"]["seed"]),
                "sector_fraction": float(manifest["mask_design"]["sector_fraction"]),
                "band_width_mm": float(manifest["mask_design"]["band_width_mm"]),
                "guard_width_mm": float(manifest["mask_design"]["guard_width_mm"]),
            }
            if _parse_manifest_integer(row["seed"], "seed", row_number) != exact_numeric["seed"]:
                raise CohortInputError(f"mask-manifest row {row_number} has a different seed")
            for field in ("sector_fraction", "band_width_mm", "guard_width_mm"):
                if _parse_manifest_float(row[field], field, row_number) != exact_numeric[field]:
                    raise CohortInputError(
                        f"mask-manifest row {row_number} differs in {field}"
                    )
            for field in (
                "valid_nodes",
                "training_nodes",
                "guard_nodes",
                "evaluation_nodes",
                "selected_boundary_nodes",
            ):
                count = _parse_manifest_integer(row[field], field, row_number)
                if count < 0 or (field in {"valid_nodes", "training_nodes", "evaluation_nodes", "selected_boundary_nodes"} and count == 0):
                    raise CohortInputError(
                        f"mask-manifest row {row_number} has invalid {field}"
                    )
            for field in ("training_area_mm2", "guard_area_mm2", "evaluation_area_mm2"):
                area = _parse_manifest_float(row[field], field, row_number)
                if area < 0.0 or (field != "guard_area_mm2" and area == 0.0):
                    raise CohortInputError(
                        f"mask-manifest row {row_number} has invalid {field}"
                    )
            if row["input_manifest_sha256"] != manifest_digest:
                raise CohortInputError(
                    f"mask-manifest row {row_number} was prepared from a different input manifest"
                )
            if row["post_mesh_sha256"] != inventory_by_id[patient_id]["post_sha256"]:
                raise CohortInputError(
                    f"mask-manifest row {row_number} was prepared from a different post mesh"
                )
            expected_plan = expected_lock_sha256 if patient_id in LOCKED_HOLDOUT_IDS else None
            if expected_plan is not None and row["analysis_plan_sha256"] != expected_plan:
                raise CohortInputError(
                    f"mask-manifest row {row_number} was not prepared under the supplied lock"
                )
            if expected_plan is None and row["analysis_plan_sha256"] not in {"", expected_lock_sha256 or ""}:
                raise CohortInputError(
                    f"mask-manifest row {row_number} has an unverified analysis-plan checksum"
                )
            if re.fullmatch(r"[0-9a-f]{64}", row["mask_sha256"]) is None:
                raise CohortInputError(
                    f"mask-manifest row {row_number} has an invalid mask checksum"
                )
            key = (patient_id, pv_label, replicate)
            primary[key] = dict(row)
    expected = {
        (patient_id, pv_label, replicate)
        for patient_id in patient_ids
        for pv_label in CANONICAL_PV_LABELS
        for replicate in range(int(manifest["mask_design"]["replicates"]))
    }
    if set(primary) != expected:
        missing = sorted(expected - set(primary))
        extra = sorted(set(primary) - expected)
        raise CohortInputError(
            f"primary prepared masks are not complete; missing={missing[:5]}, extra={extra[:5]}"
        )
    return primary


def _load_and_verify_prepared_mask(
    mask_directory: Path,
    row: Mapping[str, str],
    mesh: Any,
    barrier: np.ndarray,
    boundaries: Mapping[str, np.ndarray],
    manifest: Mapping[str, Any],
) -> PreparedMask:
    patient_id = row["patient_id"]
    pv_label = row["pv_label"]
    replicate = int(row["replicate"])
    path = _safe_child(mask_directory, row["npz_path"])
    if not path.is_file():
        raise CohortInputError(f"prepared mask does not exist: {path}")
    try:
        with np.load(path, allow_pickle=False) as archive:
            if set(archive.files) != {
                "training",
                "guard",
                "evaluation",
                "selected_boundary",
            }:
                raise CohortInputError(f"prepared mask {path} has unexpected arrays")
            training = np.asarray(archive["training"])
            guard = np.asarray(archive["guard"])
            evaluation = np.asarray(archive["evaluation"])
            selected_boundary = np.asarray(archive["selected_boundary"])
    except (OSError, ValueError) as exc:
        raise CohortInputError(f"cannot read prepared mask {path}: {exc}") from exc
    for name, values in (
        ("training", training),
        ("guard", guard),
        ("evaluation", evaluation),
    ):
        if values.dtype != np.bool_ or values.shape != (len(mesh.points),):
            raise CohortInputError(
                f"prepared mask {path} array {name} must be boolean with one entry per node"
            )
    if (
        selected_boundary.ndim != 1
        or selected_boundary.dtype.kind not in "iu"
        or np.any(selected_boundary < 0)
        or np.any(selected_boundary >= len(mesh.points))
    ):
        raise CohortInputError(f"prepared mask {path} has invalid selected_boundary")
    if np.any(training & guard) or np.any(training & evaluation) or np.any(guard & evaluation):
        raise CohortInputError(f"prepared mask {path} regions overlap")
    expected = prepare_patient_mask(
        patient_id,
        mesh,
        barrier,
        boundaries,
        manifest,
        replicate,
        pv_label,
    )
    for name, observed, wanted in (
        ("training", training, expected.training),
        ("guard", guard, expected.guard),
        ("evaluation", evaluation, expected.evaluation),
        (
            "selected_boundary",
            np.asarray(selected_boundary, dtype=np.int64),
            expected.selected_boundary,
        ),
    ):
        if not np.array_equal(observed, wanted):
            raise CohortInputError(
                f"prepared mask {path} array {name} differs from deterministic regeneration"
            )
    if row["mask_sha256"] != expected.metadata["mask_sha256"]:
        raise CohortInputError(f"prepared mask {path} checksum differs after regeneration")
    node_area = _node_area_weights(mesh)
    checks = {
        "valid_nodes": int(np.count_nonzero(np.isfinite(barrier))),
        "training_nodes": int(np.count_nonzero(expected.training)),
        "guard_nodes": int(np.count_nonzero(expected.guard)),
        "evaluation_nodes": int(np.count_nonzero(expected.evaluation)),
        "selected_boundary_nodes": int(len(expected.selected_boundary)),
    }
    for field, value in checks.items():
        if int(row[field]) != value:
            raise CohortInputError(f"prepared mask {path} metadata field {field} differs")
    area_checks = {
        "training_area_mm2": float(node_area[expected.training].sum()),
        "guard_area_mm2": float(node_area[expected.guard].sum()),
        "evaluation_area_mm2": float(node_area[expected.evaluation].sum()),
    }
    for field, value in area_checks.items():
        if not np.isclose(float(row[field]), value, rtol=2.0e-13, atol=1.0e-12):
            raise CohortInputError(f"prepared mask {path} area field {field} differs")
    return expected


def _refuse_existing_outputs(paths: Sequence[Path]) -> None:
    resolved = [path.resolve() for path in paths]
    if len(resolved) != len(set(resolved)):
        raise CohortInputError("write-once output targets must be distinct paths")
    existing = [str(path) for path in paths if path.exists()]
    if existing:
        raise CohortInputError(
            "write-once output target already exists: " + ", ".join(existing)
        )


def command_run_experiments(args: argparse.Namespace) -> None:
    """Run outcome-blind P1/P2 calculations under one locked numerical setup."""
    manifest = load_manifest(args.manifest)
    _require_primary_design(manifest)
    candidate_id = args.development_candidate_id
    numerics = load_patient_numerics(
        args.patient_numerics, require_locked=candidate_id is None
    )
    if candidate_id is not None:
        if args.partition != "development":
            raise CohortInputError(
                "development candidate configurations cannot be run on the locked holdout"
            )
        matches = [
            candidate
            for candidate in numerics["development_candidates"]
            if candidate["configuration_id"] == candidate_id
        ]
        if len(matches) != 1:
            raise CohortInputError(
                "--development-candidate-id must name exactly one declared candidate"
            )
        configuration = matches[0]
    else:
        configuration = numerics["selection"]["selected_configuration"]
    lock = _require_holdout_unlock(args)
    _check_lock_linkage(
        lock,
        args.manifest,
        manifest,
        numerics_path=args.patient_numerics,
    )
    residual_limit = float(configuration["capacity"]["relative_residual_max"])
    if lock is not None and residual_limit != float(
        lock["numerical_acceptance"]["capacity_relative_residual_max"]
    ):
        raise CohortInputError(
            "selected capacity residual threshold differs from the analysis lock"
        )
    selected_ids = _partition_ids(args.partition)
    inventory, prepared = validate_cohort(
        args.cohort_root.resolve(),
        manifest,
        patient_ids=selected_ids,
        expose_holdout_summaries=args.partition != "development",
    )
    inventory_by_id = {row["patient_id"]: row for row in inventory}
    mask_rows = _read_primary_mask_rows(
        args.masks_dir.resolve(),
        selected_ids,
        args.manifest,
        manifest,
        inventory_by_id,
        args.expected_lock_sha256 if lock is not None else None,
    )
    _refuse_existing_outputs(
        (args.metrics_output, args.phenotype_output, args.provenance_output)
    )
    metric_rows: list[dict[str, Any]] = []
    phenotype_rows: list[dict[str, Any]] = []
    annulus_width = float(configuration["capacity"]["annulus_width_mm"])
    probability_threshold = float(configuration["probability_threshold"])
    configuration_id = configuration["configuration_id"]
    for patient_id in selected_ids:
        mesh, signed_reference, boundaries = prepared[patient_id]
        partition = "development" if patient_id in DEVELOPMENT_IDS else "locked_holdout"
        domains: dict[str, CapacityDomain] = {}
        cycles: dict[str, np.ndarray] = {}
        full_capacities: dict[str, float] = {}
        for pv_label in CANONICAL_PV_LABELS:
            cycles[pv_label] = ordered_boundary_cycle(
                mesh, boundaries[pv_label], f"patient {patient_id}/{pv_label}"
            )
            domain = build_capacity_domain(
                mesh,
                boundaries[pv_label],
                np.isfinite(signed_reference),
                annulus_width,
            )
            _require_annulus_coverage(domain, f"patient {patient_id}/{pv_label}")
            domains[pv_label] = domain
            full_capacity, full_residual = capacity_from_score(
                domain, signed_reference, residual_limit
            )
            full_capacities[pv_label] = full_capacity
            widest, gap_count, minimum = _cycle_gap_metrics(
                mesh,
                cycles[pv_label],
                signed_reference,
                probability_threshold,
            )
            phenotype_rows.append(
                {
                    "patient_id": patient_id,
                    "partition": partition,
                    "configuration_id": configuration_id,
                    "estimator": "full_imaging_reference",
                    "replicate": -1,
                    "mask_variant": "full",
                    "pv_label": pv_label,
                    "annulus_width_mm": annulus_width,
                    "conductivity_map": PRIMARY_CONDUCTIVITY_MAP,
                    "conductivity_score_source": FULL_REFERENCE_SCORE,
                    "normalised_capacity": full_capacity,
                    "capacity_relative_residual": full_residual,
                    "widest_viable_arc_mm": widest,
                    "viable_arc_count": gap_count,
                    "minimum_barrier_score": minimum,
                    "phenotype_complete": 1,
                }
            )
        for pv_label in CANONICAL_PV_LABELS:
            domain = domains[pv_label]
            for replicate in range(int(manifest["mask_design"]["replicates"])):
                mask = _load_and_verify_prepared_mask(
                    args.masks_dir.resolve(),
                    mask_rows[(patient_id, pv_label, replicate)],
                    mesh,
                    signed_reference,
                    boundaries,
                    manifest,
                )
                evaluation_area = float(
                    _node_area_weights(mesh)[mask.evaluation].sum()
                )
                methods = _run_surface_methods(
                    mesh,
                    signed_reference,
                    mask,
                    domain.original_nodes,
                    configuration,
                )
                for estimator, (state, solver_residual) in methods.items():
                    metrics = _weighted_reconstruction_metrics(
                        mesh,
                        signed_reference,
                        state,
                        mask.evaluation,
                        probability_threshold,
                    )
                    capacity, capacity_residual = capacity_from_score(
                        domain, state, residual_limit
                    )
                    full_capacity = full_capacities[pv_label]
                    widest, gap_count, minimum = _cycle_gap_metrics(
                        mesh, cycles[pv_label], state, probability_threshold
                    )
                    metric_rows.append(
                        {
                            "patient_id": patient_id,
                            "partition": partition,
                            "pv_label": pv_label,
                            "replicate": replicate,
                            "mask_variant": "primary",
                            "sector_fraction": float(manifest["mask_design"]["sector_fraction"]),
                            "band_width_mm": float(manifest["mask_design"]["band_width_mm"]),
                            "evaluation_area_mm2": evaluation_area,
                            "configuration_id": configuration_id,
                            "estimator": estimator,
                            **metrics,
                            "normalised_capacity": capacity,
                            "full_normalised_capacity": full_capacity,
                            "capacity_relative_error": abs(capacity - full_capacity) / full_capacity,
                            "absolute_log_capacity_ratio": abs(
                                float(np.log(capacity / full_capacity))
                            ),
                            "solver_converged": 1,
                            "solver_residual": solver_residual,
                        }
                    )
                    phenotype_rows.append(
                        {
                            "patient_id": patient_id,
                            "partition": partition,
                            "configuration_id": configuration_id,
                            "estimator": estimator,
                            "replicate": replicate,
                            "mask_variant": "primary",
                            "pv_label": pv_label,
                            "annulus_width_mm": annulus_width,
                            "conductivity_map": PRIMARY_CONDUCTIVITY_MAP,
                            "conductivity_score_source": RECONSTRUCTION_SCORE,
                            "normalised_capacity": capacity,
                            "capacity_relative_residual": capacity_residual,
                            "widest_viable_arc_mm": widest,
                            "viable_arc_count": gap_count,
                            "minimum_barrier_score": minimum,
                            "phenotype_complete": 1,
                        }
                    )
    _write_csv(args.metrics_output, RECONSTRUCTION_METRIC_COLUMNS, metric_rows)
    _write_csv(args.phenotype_output, PHENOTYPE_COLUMNS, phenotype_rows)
    provenance = {
        "schema_version": "1.0",
        "partition": args.partition,
        "n_patients": len(selected_ids),
        "configuration_id": configuration_id,
        "configuration_mode": (
            "development_candidate" if candidate_id is not None else "locked_selection"
        ),
        "patient_input_manifest_sha256": _sha256_file(args.manifest),
        "patient_numerics_manifest_sha256": _sha256_file(args.patient_numerics),
        "analysis_lock_sha256": args.expected_lock_sha256 if lock is not None else "",
        "mask_manifest_sha256": _sha256_file(
            args.masks_dir.resolve() / "patient_mask_manifest.csv"
        ),
        "reconstruction_metrics_sha256": _sha256_file(args.metrics_output),
        "phenotype_table_sha256": _sha256_file(args.phenotype_output),
        "outcomes_accessed": False,
    }
    args.provenance_output.parent.mkdir(parents=True, exist_ok=True)
    args.provenance_output.write_text(
        json.dumps(provenance, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(
        f"completed outcome-blind P1/P2 runs for {len(selected_ids)} patients; "
        f"wrote {len(metric_rows)} metric rows and {len(phenotype_rows)} phenotype rows"
    )


def _load_locked_analysis(path: Path, expected_sha256: str) -> dict[str, Any]:
    if not re.fullmatch(r"[0-9a-f]{64}", expected_sha256):
        raise CohortInputError("--expected-lock-sha256 must be a lowercase SHA-256 digest")
    if not path.is_file() or _sha256_file(path) != expected_sha256:
        raise CohortInputError("analysis-lock checksum does not match")
    try:
        with path.open("r", encoding="utf-8") as stream:
            lock = json.load(stream, object_pairs_hook=_json_object_without_duplicates)
    except (OSError, json.JSONDecodeError) as exc:
        raise CohortInputError(f"cannot read analysis lock {path}: {exc}") from exc
    if not isinstance(lock, dict) or lock.get("schema_version") != "1.0":
        raise CohortInputError("analysis lock must be a schema-version 1.0 JSON object")
    _reject_unknown(
        lock,
        {
            "schema_version",
            "status",
            "protocol",
            "source",
            "outcome_blinding",
            "primary_settings",
            "frozen_phenotype",
            "numerical_acceptance",
            "locked_outputs",
        },
        "analysis_lock",
    )
    if lock.get("status") != "LOCKED":
        raise CohortInputError("analysis lock status must be exactly 'LOCKED'")

    def require_sha(mapping: Mapping[str, Any], field: str, context: str) -> str:
        value = mapping.get(field)
        if not isinstance(value, str) or re.fullmatch(r"[0-9a-f]{64}", value) is None:
            raise CohortInputError(f"{context}.{field} must be a lowercase SHA-256 digest")
        return value

    def require_completed(mapping: Mapping[str, Any], field: str, context: str) -> str:
        value = mapping.get(field)
        if (
            not isinstance(value, str)
            or not value.strip()
            or "REPLACE" in value.upper()
        ):
            raise CohortInputError(f"{context}.{field} is not completed")
        return value

    def require_timestamp(mapping: Mapping[str, Any], field: str, context: str) -> str:
        value = require_completed(mapping, field, context)
        if re.fullmatch(
            r"[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(?:\.[0-9]+)?Z",
            value,
        ) is None:
            raise CohortInputError(f"{context}.{field} must be an ISO-8601 UTC timestamp")
        return value

    protocol = _require_mapping(lock, "protocol")
    _reject_unknown(protocol, {"path", "sha256"}, "analysis_lock.protocol")
    require_completed(protocol, "path", "analysis_lock.protocol")
    require_sha(protocol, "sha256", "analysis_lock.protocol")

    source = _require_mapping(lock, "source")
    _reject_unknown(
        source,
        {
            "git_commit_or_tree_hash",
            "environment_lock_sha256",
            "patient_input_manifest_sha256",
            "patient_numerics_manifest_sha256",
        },
        "analysis_lock.source",
    )
    source_hash = require_completed(
        source, "git_commit_or_tree_hash", "analysis_lock.source"
    )
    if re.fullmatch(r"(?:[0-9a-f]{40}|[0-9a-f]{64})", source_hash) is None:
        raise CohortInputError(
            "analysis_lock.source.git_commit_or_tree_hash must be a 40- or 64-digit hash"
        )
    for field in (
        "environment_lock_sha256",
        "patient_input_manifest_sha256",
        "patient_numerics_manifest_sha256",
    ):
        require_sha(source, field, "analysis_lock.source")

    blinding = _require_mapping(lock, "outcome_blinding")
    _reject_unknown(
        blinding,
        {"clinical_manifest_unavailable_during_lock", "confirmed_by", "confirmed_utc"},
        "analysis_lock.outcome_blinding",
    )
    if blinding.get("clinical_manifest_unavailable_during_lock") is not True:
        raise CohortInputError(
            "analysis lock must confirm that the clinical manifest was unavailable"
        )
    require_completed(blinding, "confirmed_by", "analysis_lock.outcome_blinding")
    require_timestamp(blinding, "confirmed_utc", "analysis_lock.outcome_blinding")

    primary = _require_mapping(lock, "primary_settings")
    _reject_unknown(
        primary,
        {
            "development_size",
            "locked_holdout_size",
            "mask_seed",
            "mask_replicates",
            "masked_boundary_arc_fraction",
            "annulus_width_mm",
            "guard_width_mm",
            "reconstruction_endpoint",
            "phenotype_fidelity_endpoint",
            "recurrence_endpoint",
        },
        "analysis_lock.primary_settings",
    )
    required_primary = {
        "development_size": 67,
        "locked_holdout_size": 15,
        "mask_seed": 20250903,
        "mask_replicates": 12,
        "masked_boundary_arc_fraction": 0.5,
        "annulus_width_mm": 10.0,
        "guard_width_mm": 1.5,
        "reconstruction_endpoint": "patient_area_weighted_brier",
        "phenotype_fidelity_endpoint": "patient_median_mean_abs_log_capacity_ratio",
        "recurrence_endpoint": "locked_holdout_delta_log_loss_m1_minus_m0",
    }
    for field, expected in required_primary.items():
        if primary.get(field) != expected:
            raise CohortInputError(f"locked primary setting {field} must equal {expected!r}")
    phenotype = _require_mapping(lock, "frozen_phenotype")
    _reject_unknown(
        phenotype,
        {
            "name",
            "estimator",
            "capacity_per_rotation",
            "within_pv_rotation_aggregation",
            "across_pv_aggregation",
            "operation_order",
            "definition",
            "conductivity_map",
            "full_reference_score",
            "reconstruction_score",
            "probability_clipping_only",
            "log_offset",
            "strict_positive_capacity_required",
            "higher_means",
        },
        "analysis_lock.frozen_phenotype",
    )
    expected_fields: dict[str, Any] = {
        "name": "B_i",
        "estimator": "direct_graph_reconstruction_from_primary_50_percent_masks",
        "capacity_per_rotation": "normalized_capacity",
        "within_pv_rotation_aggregation": "median",
        "across_pv_aggregation": "maximum",
        "definition": "-log(max_pv(median_12_rotations(normalized_capacity)))",
        "conductivity_map": PRIMARY_CONDUCTIVITY_MAP,
        "full_reference_score": FULL_REFERENCE_SCORE,
        "reconstruction_score": RECONSTRUCTION_SCORE,
        "probability_clipping_only": True,
        "log_offset": 0.0,
        "strict_positive_capacity_required": True,
        "higher_means": "stronger_modeled_barrier",
    }
    for field, expected in expected_fields.items():
        if phenotype.get(field) != expected:
            raise CohortInputError(f"locked phenotype field {field} must equal {expected!r}")
    expected_order = [
        "normalized_capacity_per_rotation_per_pv",
        "median_over_12_rotations_within_each_pv",
        "maximum_over_pvs",
        "negative_log",
    ]
    if phenotype.get("operation_order") != expected_order:
        raise CohortInputError("locked phenotype operation_order differs from the declared analysis")
    numerical = _require_mapping(lock, "numerical_acceptance")
    _reject_unknown(
        numerical,
        {
            "capacity_relative_residual_max",
            "capacity_two_finest_relative_change_max",
            "whole_surface_valid_area_fraction_min",
            "pv_annulus_valid_area_fraction_min",
        },
        "analysis_lock.numerical_acceptance",
    )
    expected_numerical = {
        "capacity_relative_residual_max": 1.0e-10,
        "capacity_two_finest_relative_change_max": 0.05,
        "whole_surface_valid_area_fraction_min": WHOLE_SURFACE_VALID_AREA_FRACTION_MIN,
        "pv_annulus_valid_area_fraction_min": PV_ANNULUS_VALID_AREA_FRACTION_MIN,
    }
    for field, expected in expected_numerical.items():
        if numerical.get(field) != expected:
            raise CohortInputError(
                f"analysis_lock.numerical_acceptance.{field} must equal {expected!r}"
            )

    outputs = _require_mapping(lock, "locked_outputs")
    _reject_unknown(
        outputs,
        {"directory", "created_utc", "manifest_sha256"},
        "analysis_lock.locked_outputs",
    )
    require_completed(outputs, "directory", "analysis_lock.locked_outputs")
    require_timestamp(outputs, "created_utc", "analysis_lock.locked_outputs")
    require_sha(outputs, "manifest_sha256", "analysis_lock.locked_outputs")
    return lock


def _read_phenotype_rows(path: Path) -> list[dict[str, str]]:
    if not path.is_file():
        raise CohortInputError(f"phenotype table does not exist: {path}")
    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames is None or tuple(reader.fieldnames) != PHENOTYPE_COLUMNS:
            raise CohortInputError(
                "phenotype CSV header differs from the immutable long-form schema"
            )
        return list(reader)


def _load_run_experiment_provenance(
    path: Path,
    *,
    phenotype_path: Path,
    numerics_path: Path,
    analysis_lock_sha256: str,
    patient_input_manifest_sha256: str,
    partition: str,
    configuration_id: str,
) -> dict[str, Any]:
    try:
        with path.open("r", encoding="utf-8") as stream:
            provenance = json.load(
                stream, object_pairs_hook=_json_object_without_duplicates
            )
    except (OSError, json.JSONDecodeError) as exc:
        raise CohortInputError(f"cannot read P1/P2 run provenance {path}: {exc}") from exc
    if not isinstance(provenance, Mapping):
        raise CohortInputError("P1/P2 run provenance root must be an object")
    expected_keys = {
        "schema_version",
        "partition",
        "n_patients",
        "configuration_id",
        "configuration_mode",
        "patient_input_manifest_sha256",
        "patient_numerics_manifest_sha256",
        "analysis_lock_sha256",
        "mask_manifest_sha256",
        "reconstruction_metrics_sha256",
        "phenotype_table_sha256",
        "outcomes_accessed",
    }
    if set(provenance) != expected_keys:
        raise CohortInputError("P1/P2 run provenance has an unexpected key set")
    expected_patients = len(_partition_ids(partition))
    exact = {
        "schema_version": "1.0",
        "partition": partition,
        "n_patients": expected_patients,
        "configuration_id": configuration_id,
        "configuration_mode": "locked_selection",
        "patient_numerics_manifest_sha256": _sha256_file(numerics_path),
        "analysis_lock_sha256": analysis_lock_sha256,
        "patient_input_manifest_sha256": patient_input_manifest_sha256,
        "phenotype_table_sha256": _sha256_file(phenotype_path),
        "outcomes_accessed": False,
    }
    for field, expected in exact.items():
        if provenance.get(field) != expected:
            raise CohortInputError(
                f"P1/P2 run provenance field {field} does not match the aggregate input"
            )
    for field in (
        "mask_manifest_sha256",
        "reconstruction_metrics_sha256",
    ):
        if not isinstance(provenance.get(field), str) or re.fullmatch(
            r"[0-9a-f]{64}", provenance[field]
        ) is None:
            raise CohortInputError(f"P1/P2 run provenance field {field} is not SHA-256")
    return dict(provenance)


def command_select_numerics(args: argparse.Namespace) -> None:
    """Apply the frozen one-SE rule to complete development-only candidate runs."""
    numerics = load_patient_numerics(args.patient_numerics, require_locked=False)
    selection = numerics["selection"]
    if selection["status"] != "DRAFT_NOT_LOCKED":
        raise CohortInputError("select-numerics requires a DRAFT_NOT_LOCKED manifest")
    candidate_by_id = {
        candidate["configuration_id"]: candidate
        for candidate in numerics["development_candidates"]
    }
    if len(args.metrics) != len(args.metric_provenance):
        raise CohortInputError(
            "--metrics and --metric-provenance must supply one paired path per candidate run"
        )
    grouped: dict[tuple[str, str, str, int], tuple[float, float]] = {}
    metric_input_hashes: dict[str, str] = {}
    provenance_input_hashes: dict[str, str] = {}
    common_patient_input_hashes: set[str] = set()
    common_mask_manifest_hashes: set[str] = set()
    for path, provenance_path in zip(
        args.metrics, args.metric_provenance, strict=True
    ):
        if not path.is_file():
            raise CohortInputError(f"candidate metric table does not exist: {path}")
        try:
            with provenance_path.open("r", encoding="utf-8") as stream:
                run_provenance = json.load(
                    stream, object_pairs_hook=_json_object_without_duplicates
                )
        except (OSError, json.JSONDecodeError) as exc:
            raise CohortInputError(
                f"cannot read candidate run provenance {provenance_path}: {exc}"
            ) from exc
        expected_provenance_keys = {
            "schema_version",
            "partition",
            "n_patients",
            "configuration_id",
            "configuration_mode",
            "patient_input_manifest_sha256",
            "patient_numerics_manifest_sha256",
            "analysis_lock_sha256",
            "mask_manifest_sha256",
            "reconstruction_metrics_sha256",
            "phenotype_table_sha256",
            "outcomes_accessed",
        }
        if not isinstance(run_provenance, Mapping) or set(run_provenance) != expected_provenance_keys:
            raise CohortInputError(
                f"candidate run provenance has an unexpected key set: {provenance_path}"
            )
        configuration_id_for_file = run_provenance["configuration_id"]
        exact_provenance = {
            "schema_version": "1.0",
            "partition": "development",
            "n_patients": 67,
            "configuration_mode": "development_candidate",
            "patient_numerics_manifest_sha256": _sha256_file(args.patient_numerics),
            "analysis_lock_sha256": "",
            "reconstruction_metrics_sha256": _sha256_file(path),
            "outcomes_accessed": False,
        }
        for field, expected_value in exact_provenance.items():
            if run_provenance.get(field) != expected_value:
                raise CohortInputError(
                    f"candidate run provenance field {field} is inconsistent: {provenance_path}"
                )
        if configuration_id_for_file not in candidate_by_id:
            raise CohortInputError(
                f"candidate run provenance names an undeclared configuration: {provenance_path}"
            )
        for field in (
            "patient_input_manifest_sha256",
            "mask_manifest_sha256",
            "phenotype_table_sha256",
        ):
            if not isinstance(run_provenance.get(field), str) or re.fullmatch(
                r"[0-9a-f]{64}", run_provenance[field]
            ) is None:
                raise CohortInputError(
                    f"candidate run provenance field {field} is not SHA-256"
                )
        metric_input_hashes[str(path)] = _sha256_file(path)
        provenance_input_hashes[str(provenance_path)] = _sha256_file(provenance_path)
        common_patient_input_hashes.add(run_provenance["patient_input_manifest_sha256"])
        common_mask_manifest_hashes.add(run_provenance["mask_manifest_sha256"])
        with path.open("r", encoding="utf-8-sig", newline="") as stream:
            reader = csv.DictReader(stream)
            if reader.fieldnames is None or tuple(reader.fieldnames) != RECONSTRUCTION_METRIC_COLUMNS:
                raise CohortInputError(
                    f"candidate metric header differs from the immutable schema: {path}"
                )
            for row_number, row in enumerate(reader, start=2):
                if row["configuration_id"] != configuration_id_for_file:
                    raise CohortInputError(
                        f"{path} row {row_number} differs from its run-provenance configuration"
                    )
                patient_id = row["patient_id"]
                if patient_id not in DEVELOPMENT_IDS or row["partition"] != "development":
                    raise CohortInputError(
                        f"{path} row {row_number} is not development-only"
                    )
                if row["estimator"] != "graph" or row["mask_variant"] != "primary":
                    continue
                configuration_id = row["configuration_id"]
                if configuration_id not in candidate_by_id:
                    raise CohortInputError(
                        f"{path} row {row_number} uses an undeclared candidate"
                    )
                pv_label = row["pv_label"]
                if pv_label not in CANONICAL_PV_LABELS:
                    raise CohortInputError(f"{path} row {row_number} has an unknown PV")
                try:
                    replicate = int(row["replicate"])
                    fraction = float(row["sector_fraction"])
                    band = float(row["band_width_mm"])
                    area = float(row["evaluation_area_mm2"])
                    brier = float(row["brier_area_weighted"])
                    converged = int(row["solver_converged"])
                except ValueError as exc:
                    raise CohortInputError(
                        f"{path} row {row_number} has a non-numeric selection field"
                    ) from exc
                if (
                    not 0 <= replicate < 12
                    or fraction != 0.5
                    or band != 10.0
                    or not np.isfinite(area)
                    or area <= 0.0
                    or not np.isfinite(brier)
                    or not 0.0 <= brier <= 1.0
                    or converged != 1
                ):
                    raise CohortInputError(
                        f"{path} row {row_number} is not a complete accepted primary run"
                    )
                key = (configuration_id, patient_id, pv_label, replicate)
                if key in grouped:
                    raise CohortInputError(f"duplicate candidate metric row for {key}")
                grouped[key] = (area, brier)
    if len(common_patient_input_hashes) != 1 or len(common_mask_manifest_hashes) != 1:
        raise CohortInputError(
            "all candidate runs must use the same patient-input and mask manifests"
        )
    expected = {
        (configuration_id, patient_id, pv_label, replicate)
        for configuration_id in candidate_by_id
        for patient_id in DEVELOPMENT_IDS
        for pv_label in CANONICAL_PV_LABELS
        for replicate in range(12)
    }
    if set(grouped) != expected:
        missing = sorted(expected - set(grouped))
        extra = sorted(set(grouped) - expected)
        raise CohortInputError(
            f"development candidate grid is incomplete; missing={missing[:5]}, extra={extra[:5]}"
        )
    summaries: dict[str, dict[str, float]] = {}
    for configuration_id in candidate_by_id:
        patient_scores: list[float] = []
        for patient_id in DEVELOPMENT_IDS:
            observations = [
                grouped[(configuration_id, patient_id, pv_label, replicate)]
                for pv_label in CANONICAL_PV_LABELS
                for replicate in range(12)
            ]
            areas = np.asarray([value[0] for value in observations], dtype=float)
            scores = np.asarray([value[1] for value in observations], dtype=float)
            patient_scores.append(float(np.dot(areas, scores) / areas.sum()))
        values = np.asarray(patient_scores, dtype=float)
        summaries[configuration_id] = {
            "mean_patient_area_weighted_brier": float(np.mean(values)),
            "standard_error_across_patients": float(
                np.std(values, ddof=1) / np.sqrt(len(values))
            ),
        }
    best_id = min(
        candidate_by_id,
        key=lambda identifier: (
            summaries[identifier]["mean_patient_area_weighted_brier"], identifier
        ),
    )
    threshold = (
        summaries[best_id]["mean_patient_area_weighted_brier"]
        + summaries[best_id]["standard_error_across_patients"]
    )
    eligible = {
        identifier
        for identifier, summary in summaries.items()
        if summary["mean_patient_area_weighted_brier"] <= threshold
    }
    selected_id = next(
        identifier
        for identifier in selection["complexity_order"]
        if identifier in eligible
    )
    _refuse_existing_outputs((args.output, args.report_output))
    report = {
        "schema_version": "1.0",
        "scope": "development_only_numerical_selection",
        "rule": "one_standard_error_patient_level_brier",
        "best_mean_configuration_id": best_id,
        "one_standard_error_threshold": threshold,
        "selected_configuration_id": selected_id,
        "complexity_order": selection["complexity_order"],
        "candidate_summary": summaries,
        "metric_input_sha256": metric_input_hashes,
        "metric_run_provenance_sha256": provenance_input_hashes,
        "source_draft_numerics_sha256": _sha256_file(args.patient_numerics),
        "patient_input_manifest_sha256": next(iter(common_patient_input_hashes)),
        "mask_manifest_sha256": next(iter(common_mask_manifest_hashes)),
        "n_development_patients": 67,
        "outcomes_accessed": False,
    }
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    locked = json.loads(json.dumps(numerics))
    locked["selection"]["status"] = "LOCKED"
    locked["selection"]["selected_configuration"] = candidate_by_id[selected_id]
    locked["selection"]["selection_evidence"] = {
        "source_draft_numerics_sha256": _sha256_file(args.patient_numerics),
        "selection_report_sha256": _sha256_file(args.report_output),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(locked, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    # Re-read what was written so the production validator, not this function's
    # in-memory assumptions, certifies the lock.
    load_patient_numerics(args.output, require_locked=True)
    print(
        f"selected {selected_id!r} by the development-only one-SE rule; "
        f"locked numerics written to {args.output}"
    )


def command_aggregate_phenotype(args: argparse.Namespace) -> None:
    """Collapse outcome-blind capacities to the single locked recurrence feature."""
    lock = _load_locked_analysis(args.analysis_lock, args.expected_lock_sha256)
    numerics = load_patient_numerics(args.patient_numerics)
    if lock["source"]["patient_numerics_manifest_sha256"] != _sha256_file(
        args.patient_numerics
    ):
        raise CohortInputError(
            "analysis lock does not identify the supplied patient-numerics manifest"
        )
    selected_configuration_id = numerics["selection"]["selected_configuration"][
        "configuration_id"
    ]
    _load_run_experiment_provenance(
        args.input_provenance,
        phenotype_path=args.input,
        numerics_path=args.patient_numerics,
        analysis_lock_sha256=args.expected_lock_sha256,
        patient_input_manifest_sha256=lock["source"]["patient_input_manifest_sha256"],
        partition=args.partition,
        configuration_id=selected_configuration_id,
    )
    if args.partition != "development" and not args.unlock_locked_holdout:
        raise CohortInputError(
            "locked holdout phenotype requested without --unlock-locked-holdout"
        )
    rows = _read_phenotype_rows(args.input)
    selected_ids = _partition_ids(args.partition)
    residual_limit = float(lock["numerical_acceptance"]["capacity_relative_residual_max"])
    grouped: dict[tuple[str, str, int], float] = {}
    for row_number, row in enumerate(rows, start=2):
        patient_id = row["patient_id"]
        if patient_id not in EXPECTED_IDS:
            raise CohortInputError(
                f"phenotype row {row_number} has unexpected patient {patient_id!r}"
            )
        expected_partition = (
            "development" if patient_id in DEVELOPMENT_IDS else "locked_holdout"
        )
        if row["partition"] != expected_partition:
            raise CohortInputError(f"phenotype row {row_number} has an incorrect partition")
        # Sensitivity variants and passive/screened estimators may coexist in
        # the long table.  Only the outcome-blind primary graph rows enter B_i.
        if not (
            row["estimator"] == "graph"
            and row["mask_variant"] == "primary"
            and row["conductivity_map"] == PRIMARY_CONDUCTIVITY_MAP
            and row["conductivity_score_source"] == RECONSTRUCTION_SCORE
        ):
            continue
        if row["configuration_id"] != selected_configuration_id:
            raise CohortInputError(
                f"phenotype row {row_number} uses a non-selected numerical configuration"
            )
        try:
            replicate = int(row["replicate"])
            annulus_width = float(row["annulus_width_mm"])
            capacity = float(row["normalised_capacity"])
            residual = float(row["capacity_relative_residual"])
            complete = int(row["phenotype_complete"])
        except ValueError as exc:
            raise CohortInputError(f"phenotype row {row_number} has a non-numeric field") from exc
        if annulus_width != 10.0 or not 0 <= replicate < 12:
            raise CohortInputError(f"phenotype row {row_number} violates the primary design")
        if row["pv_label"] not in CANONICAL_PV_LABELS:
            raise CohortInputError(f"phenotype row {row_number} has an unknown PV label")
        if complete != 1 or not np.isfinite(capacity) or capacity <= 0.0:
            raise CohortInputError(
                f"phenotype row {row_number} is incomplete or has nonpositive capacity"
            )
        if not np.isfinite(residual) or residual > residual_limit:
            raise CohortInputError(
                f"phenotype row {row_number} exceeds the locked capacity residual limit"
            )
        key = (patient_id, row["pv_label"], replicate)
        if key in grouped:
            raise CohortInputError(f"duplicate primary phenotype row for {key}")
        grouped[key] = capacity

    output_rows: list[dict[str, Any]] = []
    for patient_id in selected_ids:
        pv_medians: list[float] = []
        for label in CANONICAL_PV_LABELS:
            capacities = [grouped.get((patient_id, label, replicate)) for replicate in range(12)]
            if any(value is None for value in capacities):
                raise CohortInputError(
                    f"patient {patient_id}/{label} lacks one or more of 12 primary graph rotations"
                )
            pv_medians.append(float(np.median(np.asarray(capacities, dtype=float))))
        leakage_index = max(pv_medians)
        if not np.isfinite(leakage_index) or leakage_index <= 0.0:
            raise CohortInputError(f"patient {patient_id} has a nonpositive leakage index")
        output_rows.append(
            {
                "patient_id": patient_id,
                "pvi_barrier_strength": float(-np.log(leakage_index)),
            }
        )
    provenance_path = args.output.with_suffix(args.output.suffix + ".provenance.json")
    if args.partition != "development":
        _refuse_existing_outputs((args.output, provenance_path))
    _write_csv(args.output, AGGREGATED_PHENOTYPE_COLUMNS, output_rows)
    if args.partition == "all":
        provenance = {
            "schema_version": "1.0",
            "scope": "complete_locked_cohort",
            "n_patients": 82,
            "feature": "pvi_barrier_strength",
            "definition": "-log(max_pv(median_12_rotations(normalized_capacity)))",
            "analysis_lock_sha256": args.expected_lock_sha256,
            "phenotype_table_sha256": _sha256_file(args.output),
            "long_form_phenotype_sha256": _sha256_file(args.input),
            "run_provenance_sha256": _sha256_file(args.input_provenance),
            "outcomes_accessed": False,
        }
    else:
        provenance = {
            "schema_version": "1.0",
            "scope": f"{args.partition}_upstream_partition",
            "n_patients": len(output_rows),
            "feature": "pvi_barrier_strength",
            "definition": "-log(max_pv(median_12_rotations(normalized_capacity)))",
            "analysis_lock_sha256": args.expected_lock_sha256,
            "phenotype_table_sha256": _sha256_file(args.output),
            "long_form_phenotype_sha256": _sha256_file(args.input),
            "run_provenance_sha256": _sha256_file(args.input_provenance),
            "outcomes_accessed": False,
        }
    provenance_path.write_text(
        json.dumps(provenance, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(
        f"wrote {len(output_rows)} outcome-blind patient phenotypes to {args.output}"
    )


def _synthetic_four_pv_surface():
    try:
        from surface_mesh import TriangleMesh
    except ImportError as exc:
        raise CohortInputError("surface_mesh.py is required for the synthetic dry-run") from exc
    size = 61
    points = np.asarray(
        [(float(x), float(y), 0.0) for y in range(size) for x in range(size)],
        dtype=float,
    )
    holes = (
        (15, 18, 15, 18),
        (43, 46, 15, 18),
        (15, 18, 43, 46),
        (43, 46, 43, 46),
    )
    triangles: list[tuple[int, int, int]] = []
    for y in range(size - 1):
        for x in range(size - 1):
            if any(x0 <= x < x1 and y0 <= y < y1 for x0, x1, y0, y1 in holes):
                continue
            lower_left = y * size + x
            lower_right = lower_left + 1
            upper_left = lower_left + size
            upper_right = upper_left + 1
            triangles.extend(
                (
                    (lower_left, lower_right, upper_right),
                    (lower_left, upper_right, upper_left),
                )
            )
    triangles_array = np.asarray(triangles, dtype=np.int64)
    used = np.unique(triangles_array)
    remap = np.full(len(points), -1, dtype=np.int64)
    remap[used] = np.arange(len(used), dtype=np.int64)
    points = points[used]
    triangles_array = remap[triangles_array]
    score = np.tanh(
        1.2 * (np.sin(0.32 * points[:, 0]) + np.cos(0.27 * points[:, 1]) - 0.15)
    )
    mesh = TriangleMesh(
        points,
        triangles_array,
        point_data={"signed_barrier": score},
    )
    mesh.assert_valid(require_connected=True)
    edges, counts = _edge_table(triangles_array)
    boundary_edges = edges[counts == 1]
    rows = np.r_[boundary_edges[:, 0], boundary_edges[:, 1]]
    columns = np.r_[boundary_edges[:, 1], boundary_edges[:, 0]]
    graph = coo_matrix(
        (np.ones(len(rows)), (rows, columns)),
        shape=(len(points), len(points)),
    ).tocsr()
    component_count, component_labels = connected_components(graph, directed=False)
    degrees = np.diff(graph.indptr)
    components = [
        np.flatnonzero((component_labels == component) & (degrees > 0)).astype(np.int64)
        for component in range(component_count)
    ]
    components = [component for component in components if len(component)]
    if len(components) != 5:
        raise CohortInputError("synthetic four-hole mesh does not have five boundary loops")
    pv_components = sorted(components, key=len)[:4]
    pv_components.sort(
        key=lambda nodes: (
            float(np.mean(points[nodes, 1])),
            float(np.mean(points[nodes, 0])),
        )
    )
    boundaries = {
        label: nodes for label, nodes in zip(CANONICAL_PV_LABELS, pv_components, strict=True)
    }
    return mesh, score, boundaries



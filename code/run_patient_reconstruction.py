"""Fail-closed entry point for the 82-case Dryad atrial-mesh extension.

This module keeps cohort preparation, development-only numerical selection, and
locked execution as explicit stages.  It checks the fixed development/holdout
split, resolves every PreAbl/PostAbl pair, validates declared point/cell-array
semantics, verifies explicit pulmonary-vein boundary cycles, constructs
deterministic spatial masks, and runs the declared surface methods.  It never
infers scar arrays or pulmonary-vein labels from convenient-looking names.

The declared reference barrier is normalised to ``b in [0,1]`` and supplied to
the PDE as the signed datum ``q=2b-1``.  The PDE state itself is not clipped.
Only probabilistic scoring uses ``b_hat=(1+clip(u,-1,1))/2``.
Capacity uses ``eta(s)=1e-3+(1-1e-3)/(1+exp(8s))`` with ``s=q`` for the full
imaging reference and the unclipped reconstructed state ``s=u`` for an
estimator.  Probability clipping never enters this conductivity map.

The public reproducibility package does not contain the Dryad meshes.  Thus no
patient result is generated by the publication drivers.  With separately
downloaded data, use ``validate`` first and retain its inventory before any
reconstruction is run.  The locked 15-case holdout cannot be prepared without
an explicit unlock flag and a frozen analysis-plan checksum.
"""


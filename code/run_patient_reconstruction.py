def load_patient_numerics(path: Path, *, require_locked: bool = True) -> dict[str, Any]:
    try:
        with path.open("r", encoding="utf-8") as stream:
            numerics = json.load(stream, object_pairs_hook=_json_object_without_duplicates)
    except (OSError, json.JSONDecodeError) as exc:
        raise CohortInputError(f"cannot read patient numerics manifest {path}: {exc}") from exc
    if not isinstance(numerics, Mapping):
        raise CohortInputError("patient numerics manifest root must be an object")
    _reject_unknown(
        numerics, {"schema_version", "development_candidates", "selection"}, "patient_numerics"
    )
    if numerics.get("schema_version") != "1.0":
        raise CohortInputError("patient numerics schema_version must be '1.0'")
    candidates = numerics.get("development_candidates")
    if not isinstance(candidates, list) or not candidates:
        raise CohortInputError("patient numerics needs a non-empty development candidate grid")
    identifiers: list[str] = []
    for index, candidate in enumerate(candidates):
        if not isinstance(candidate, Mapping):
            raise CohortInputError(f"development candidate {index} must be an object")
        _validate_numerical_configuration(candidate, f"development_candidates[{index}]")
        identifiers.append(candidate["configuration_id"])
    if len(identifiers) != len(set(identifiers)):
        raise CohortInputError("development candidate identifiers are not unique")
    selection = _require_mapping(numerics, "selection")
    _reject_unknown(
        selection,
        {
            "status",
            "rule",
            "selected_without_holdout",
            "complexity_order",
            "selected_configuration",
            "selection_evidence",
        },
        "patient_numerics.selection",
    )
    status = selection.get("status")
    if status not in {"DRAFT_NOT_LOCKED", "LOCKED"}:
        raise CohortInputError("patient numerics selection has an unknown status")
    if require_locked and status != "LOCKED":
        raise CohortInputError("selected numerical configuration is not LOCKED")
    if selection.get("rule") != "one_standard_error_patient_level_brier":
        raise CohortInputError("numerical selection rule must be the patient-level one-SE rule")
    if selection.get("selected_without_holdout") is not True:
        raise CohortInputError("numerical selection must certify that the holdout was unavailable")
    complexity_order = _require_exact_string_list(
        selection.get("complexity_order"), "patient_numerics.selection.complexity_order"
    )
    if set(complexity_order) != set(identifiers) or len(complexity_order) != len(identifiers):
        raise CohortInputError(
            "selection.complexity_order must list every candidate exactly once, simplest first"
        )
    selected = selection.get("selected_configuration")
    evidence = selection.get("selection_evidence")
    if status == "DRAFT_NOT_LOCKED":
        if selected is not None or evidence is not None:
            raise CohortInputError(
                "draft numerical selection must use selected_configuration=null and "
                "selection_evidence=null"
            )
    else:
        if not isinstance(selected, Mapping):
            raise CohortInputError("LOCKED selection requires selected_configuration")
        _validate_numerical_configuration(
            selected, "patient_numerics.selection.selected_configuration"
        )
        matches = [
            candidate
            for candidate in candidates
            if candidate["configuration_id"] == selected["configuration_id"]
        ]
        if len(matches) != 1 or matches[0] != selected:
            raise CohortInputError(
                "selected configuration must exactly equal one development candidate"
            )
        if not isinstance(evidence, Mapping):
            raise CohortInputError("LOCKED selection requires selection_evidence")
        _reject_unknown(
            evidence,
            {"source_draft_numerics_sha256", "selection_report_sha256"},
            "patient_numerics.selection.selection_evidence",
        )
        for name in ("source_draft_numerics_sha256", "selection_report_sha256"):
            value = evidence.get(name)
            if (
                not isinstance(value, str)
                or re.fullmatch(r"[0-9a-f]{64}", value) is None
                or value == "0" * 64
            ):
                raise CohortInputError(
                    f"patient_numerics.selection.selection_evidence.{name} must be SHA-256"
                )
    return dict(numerics)


def _validate_pv_source(source: Mapping[str, Any]) -> None:
    source_format = source.get("format")
    if source_format == "table_csv":
        _reject_unknown(
            source,
            {"format", "path", "columns", "index_base", "index_space"},
            "pv_boundaries.source",
        )
        if not isinstance(source.get("path"), str) or not source["path"]:
            raise CohortInputError("pv_boundaries.source.path must be a non-empty string")
        columns = _require_mapping(source, "columns")
        if set(columns) != {"patient_id", "pv_label", "node_id"}:
            raise CohortInputError(
                "pv_boundaries.source.columns must map patient_id, pv_label, and node_id"
            )
        if any(not isinstance(value, str) or not value for value in columns.values()):
            raise CohortInputError("PV table column names must be non-empty strings")
    elif source_format == "inline":
        _reject_unknown(
            source,
            {"format", "per_patient", "index_base", "index_space"},
            "pv_boundaries.source",
        )
        if not isinstance(source.get("per_patient"), Mapping):
            raise CohortInputError("pv_boundaries.source.per_patient must be an object")
    elif source_format == "post_point_tag":
        _reject_unknown(
            source,
            {"format", "array", "association", "tag_values"},
            "pv_boundaries.source",
        )
        if source.get("association") != "point":
            raise CohortInputError("post_point_tag association must explicitly be 'point'")
        if not isinstance(source.get("array"), str) or not source["array"]:
            raise CohortInputError("post_point_tag array must be a non-empty exact name")
        tag_values = source.get("tag_values")
        if not isinstance(tag_values, Mapping) or set(tag_values) != set(CANONICAL_PV_LABELS):
            raise CohortInputError(
                "post_point_tag tag_values must map the four canonical PV labels in fixed order"
            )
        if any(not isinstance(value, list) or not value for value in tag_values.values()):
            raise CohortInputError("each post_point_tag PV label needs at least one explicit tag value")
        flat_tags = [tag for values in tag_values.values() for tag in values]
        if not all(
            isinstance(value, (int, float))
            and not isinstance(value, bool)
            and np.isfinite(value)
            for value in flat_tags
        ):
            raise CohortInputError("post_point_tag values must be finite numbers")
        if len(flat_tags) != len(set(flat_tags)):
            raise CohortInputError("post_point_tag values must be disjoint across PV labels")
    else:
        raise CohortInputError(
            "pv_boundaries.source.format must be table_csv, inline, or post_point_tag"
        )
    if source_format in {"table_csv", "inline"} and source.get("index_base") not in {0, 1}:
        raise CohortInputError("PV node index_base must explicitly be 0 or 1")
    if source_format in {"table_csv", "inline"} and source.get("index_space") not in {
        "surface",
        "original_file",
    }:
        raise CohortInputError("PV node index_space must be 'surface' or 'original_file'")


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _verify_declared_archives(root: Path, manifest: Mapping[str, Any]) -> None:
    for archive in manifest["dataset"].get("archives", []):
        path = _safe_child(root, archive["path"])
        if not path.is_file():
            raise CohortInputError(f"declared source archive is absent: {path}")
        observed = _sha256_file(path)
        if observed.lower() != archive["sha256"].lower():
            raise CohortInputError(
                f"source archive checksum differs for {archive['path']}: "
                f"expected {archive['sha256']}, observed {observed}"
            )


def _stable_fraction(*parts: object) -> float:
    payload = "\x1f".join(str(part) for part in parts).encode("utf-8")
    integer = int.from_bytes(hashlib.sha256(payload).digest()[:8], byteorder="big")
    return integer / float(2**64)


def _safe_child(root: Path, relative: str) -> Path:
    rel = Path(relative)
    if rel.is_absolute() or ".." in rel.parts:
        raise CohortInputError(f"path must be relative to cohort root: {relative!r}")
    candidate = (root / rel).resolve()
    try:
        candidate.relative_to(root.resolve())
    except ValueError as exc:
        raise CohortInputError(f"path escapes cohort root: {relative!r}") from exc
    return candidate


def discover_mesh_pairs(root: Path, manifest: Mapping[str, Any]) -> dict[str, MeshPair]:
    """Resolve exactly 82 unique PreAbl/PostAbl mesh pairs."""
    if not root.is_dir():
        raise CohortInputError(f"cohort root is not a directory: {root}")
    discovery = manifest["mesh_discovery"]
    regex = re.compile(discovery["regex"])
    stage_tokens = discovery["stage_tokens"]
    candidates = sorted(path for path in root.glob(discovery["glob"]) if path.is_file())
    if not candidates:
        raise CohortInputError(
            f"mesh glob {discovery['glob']!r} found no files below {root}"
        )
    found: dict[str, dict[str, Path]] = {}
    unmatched: list[str] = []
    for path in candidates:
        relative = path.relative_to(root).as_posix()
        # The declared regular expression applies to a basename.  Directory
        # structure is controlled separately by the glob, and duplicates in
        # different directories remain an error below.
        match = regex.fullmatch(path.name)
        if match is None:
            unmatched.append(relative)
            continue
        patient_id = match.group("patient_id")
        stage_token = match.group("stage")
        if patient_id not in EXPECTED_IDS:
            raise CohortInputError(f"matched unexpected patient identifier {patient_id!r}: {relative}")
        if stage_token not in stage_tokens:
            raise CohortInputError(
                f"matched undeclared stage token {stage_token!r} in {relative}"
            )
        stage = stage_tokens[stage_token]
        patient_files = found.setdefault(patient_id, {})
        if stage in patient_files:
            raise CohortInputError(
                f"ambiguous {stage} mesh for patient {patient_id}: "
                f"{patient_files[stage].relative_to(root)} and {relative}"
            )
        resolved = path.resolve()
        try:
            resolved.relative_to(root.resolve())
        except ValueError as exc:
            raise CohortInputError(f"mesh symlink escapes the cohort root: {relative}") from exc
        patient_files[stage] = resolved
    if unmatched and not discovery["allow_unmatched"]:
        preview = ", ".join(unmatched[:5])
        suffix = " ..." if len(unmatched) > 5 else ""
        raise CohortInputError(
            f"{len(unmatched)} globbed mesh file(s) did not match the declared regex: {preview}{suffix}"
        )
    missing = [
        f"{patient_id}:{stage}"
        for patient_id in EXPECTED_IDS
        for stage in ("pre", "post")
        if stage not in found.get(patient_id, {})
    ]
    if missing:
        raise CohortInputError(
            "cohort is not the declared 82 paired cases; missing " + ", ".join(missing[:20])
        )
    if set(found) != set(EXPECTED_IDS):
        raise CohortInputError("discovered patient set differs from the fixed 82-case cohort")
    return {
        patient_id: MeshPair(patient_id, found[patient_id]["pre"], found[patient_id]["post"])
        for patient_id in EXPECTED_IDS
    }


